class SystemReminderMiddleware(ChatMiddleware):
    """Appends trailing ``<system-reminder>`` content before each LLM call.

    Each LLM call in the tool loop sees a fresh enriched user message
    whose original user contents come first, followed by stable turn-level
    reminders.  Exact reserved reminder tags in user-role text are escaped in
    the per-call ``ChatContext.messages`` copy; tool results are passed through
    unchanged.  ``prepped_messages`` and session state are never modified.
    """

    def __init__(
        self,
        runtime: SessionEnvironment | None = None,
        *,
        max_context_tokens: int = DEFAULT_MAX_CONTEXT_TOKENS,
        warn_threshold_pct: float = 0.50,
        sub_agent_names: list[str] | None = None,
        shell_tool_enabled: bool = False,
        tool_names: list[str] | None = None,
        session_root: Path | None = None,
        file_read_available: bool = False,
        spill_quota: SpillQuota | None = None,
        catalog_pointer_enabled: bool = True,
        skill_catalog_provider: Callable[[], str | None] | None = None,
        todo_state_provider: Callable[[], str | None] | None = None,
        mcp_instructions_provider: Callable[[], str | None] | None = None,
        file_change_provider: Callable[[], str | None] | None = None,
    ) -> None:
        self._runtime = runtime
        self._max_context_tokens = max_context_tokens
        self._warn_threshold_pct = warn_threshold_pct
        self._sub_agent_names = sub_agent_names
        self._shell_tool_enabled = shell_tool_enabled
        self._tool_names = self._dedupe_tool_names(tool_names)
        self._session_root = session_root
        self._file_read_available = file_read_available
        self._spill_quota = spill_quota
        self._catalog_pointer_enabled = catalog_pointer_enabled
        self._catalog_pointer_record_count = 0
        self._catalog_pointer_path: str | None = None
        self._catalog_pointer_snapshot_valid = False
        self._skill_catalog_provider = skill_catalog_provider
        self._todo_state_provider = todo_state_provider
        self._mcp_instructions_provider = mcp_instructions_provider
        self._file_change_provider = file_change_provider
        self._pending_switch: dict[str, str] | None = None
        self._consumed_switch_to: str | None = None
        self._pending_hook_reminders: list[str] = []
        self._next_current_run_scope_id = 1
        self._current_run_scopes: set[CurrentRunReminderScope] = set()
        self._pending_current_run_hook_reminders: dict[CurrentRunReminderScope, list[str]] = {}
        self._active_turn_scope: CurrentRunReminderScope | None = None
        self._current_run_reminder_generation = 0
        state_var_base = f"chrys_system_reminder_{id(self)}"
        self._turn_state: ContextVar[_TurnReminderState | None] = ContextVar(
            f"{state_var_base}_turn_state",
            default=None,
        )
        # Engine lifecycle permits only one active main turn per middleware instance.
        # This fallback lets child/sibling tasks recover the shared state for that turn.
        self._active_turn_state: _TurnReminderState | None = None
        # LAST_WORDS note restored from persisted session state (session
        # resume).  Consumed by the next preserving ``prepare_turn`` so a
        # post-restart retry/continue re-injects the note exactly like an
        # in-process retry; discarded when a fresh turn starts instead.
        self._restored_last_words: str | None = None
        # Todo-list text captured alongside a restored LAST_WORDS note (same
        # single-shot lifecycle as ``_restored_last_words``).
        self._restored_last_words_todo: str | None = None
        self._restored_last_words_manifest: list[dict[str, Any]] | None = None
        self._restored_last_words_breaker: dict[str, Any] | None = None
        self._restored_catalog_pointer_record_count: int | None = None

    def prepare_turn(
        self,
        *,
        reminder_scope: CurrentRunReminderScope | None = None,
        usage: Mapping[str, Any] | None = None,
        preserve_last_words: bool = False,
        preserve_turn_reminders: bool = False,
    ) -> None:
        """Prepare reminder state before ``executor.run()`` or retry/resume.

        ``preserve_last_words`` carries Phase 4 progress across retries.
        ``preserve_turn_reminders`` keeps runtime/usage/switch text
        byte-identical for KV-cache continuity on retry.
        """
        previous = self._current_turn_state()
        snapshot_catalog_pointer = False
        if preserve_turn_reminders and previous is not None:
            turn_reminders = previous.turn_reminders
            skill_catalog = previous.skill_catalog
            mcp_instructions = previous.mcp_instructions
            switch = previous.switch
        else:
            reminders, switch = self._snapshot_turn_reminders(usage=usage or {})
            turn_reminders = tuple(reminders)
            skill_catalog = self._snapshot_skill_catalog()
            mcp_instructions = self._snapshot_mcp_instructions()
            snapshot_catalog_pointer = True
        self._current_run_reminder_generation += 1
        if reminder_scope is not None:
            scoped_reminders = self._pending_current_run_hook_reminders.pop(reminder_scope, [])
            if scoped_reminders:
                turn_reminders = (*turn_reminders, *scoped_reminders)
        if self._pending_hook_reminders:
            turn_reminders = (*turn_reminders, *self._pending_hook_reminders)
            self._pending_hook_reminders.clear()
        last_words: str | None = None
        last_words_todo: str | None = None
        last_words_manifest: list[dict[str, Any]] | None = None
        last_words_breaker: dict[str, Any] | None = None
        context_pressure_notified = False
        if preserve_last_words:
            if previous is not None:
                last_words = previous.last_words
                last_words_todo = previous.last_words_todo
                last_words_manifest = list(previous.last_words_manifest or []) or None
                last_words_breaker = dict(previous.last_words_breaker) if previous.last_words_breaker else None
                context_pressure_notified = previous.context_pressure_notified
            else:
                # Post-restart retry/continue: no in-memory turn state exists,
                # fall back to the key family restored from persisted state.
                last_words = self._restored_last_words
                last_words_todo = self._restored_last_words_todo
                last_words_manifest = list(self._restored_last_words_manifest or []) or None
                last_words_breaker = (
                    dict(self._restored_last_words_breaker) if self._restored_last_words_breaker else None
                )
        if snapshot_catalog_pointer:
            restored_pointer_count = (
                self._restored_catalog_pointer_record_count if preserve_last_words and previous is None else None
            )
            if restored_pointer_count is not None:
                self._set_catalog_pointer_snapshot(restored_pointer_count)
            else:
                # Legacy restored sessions did not persist the turn-start
                # snapshot. Excluding the bounded active manifest is the best
                # compatible approximation, but new saves never rely on it.
                active_manifest_paths = {
                    entry.relative_path
                    for value in last_words_manifest or []
                    if (entry := ManifestEntry.from_state(value)) is not None and entry.relative_path
                }
                self._snapshot_catalog_pointer(excluded_relative_paths=active_manifest_paths)
        # Single-shot either way: a preserving turn consumed it; a fresh turn
        # discards it (matching the in-process new-turn semantics).
        self._restored_last_words = None
        self._restored_last_words_todo = None
        self._restored_last_words_manifest = None
        self._restored_last_words_breaker = None
        self._restored_catalog_pointer_record_count = None
        state = _TurnReminderState(
            turn_reminders=turn_reminders,
            skill_catalog=skill_catalog,
            mcp_instructions=mcp_instructions,
            switch=switch,
            file_change=self._snapshot_file_change(),
            last_words=last_words,
            last_words_todo=last_words_todo,
            last_words_manifest=last_words_manifest,
            last_words_breaker=last_words_breaker,
            context_pressure_notified=context_pressure_notified,
        )
        self._turn_state.set(state)
        self._active_turn_state = state
        self._active_turn_scope = reminder_scope
        self._consumed_switch_to = None

    def take_undelivered_file_change(self) -> str | None:
        """Pop the prepared notice unless a model-bound request already carried it."""
        state = self._current_turn_state()
        if state is None:
            return None
        notice = state.file_change
        state.file_change = None
        if state.file_change_delivered:
            return None
        return notice

    def create_current_run_scope(self) -> CurrentRunReminderScope:
        """Allocate a service-owned reminder scope for a logical main-agent run."""
        scope = CurrentRunReminderScope(self._next_current_run_scope_id)
        self._next_current_run_scope_id += 1
        self._current_run_scopes.add(scope)
        return scope

    def capture_current_run_target(
        self,
        reminder_scope: CurrentRunReminderScope,
    ) -> CurrentRunReminderTarget | None:
        """Capture a current-run reminder target if *reminder_scope* is still valid."""
        if reminder_scope not in self._current_run_scopes:
            return None
        if self._active_turn_scope is reminder_scope and self._active_turn_state is not None:
            return CurrentRunReminderTarget(
                scope=reminder_scope,
                phase="prepared",
                generation=self._current_run_reminder_generation,
                state=self._active_turn_state,
            )
        return CurrentRunReminderTarget(
            scope=reminder_scope,
            phase="pre_prepare",
            generation=self._current_run_reminder_generation,
        )

    def queue_hook_reminders_for_current_run(
        self,
        target: CurrentRunReminderTarget,
        reminders: list[str],
    ) -> bool:
        """Queue hook reminders only if the captured current-run target is still valid."""
        if not self._is_current_run_target_valid(target):
            return False
        clean = [reminder for reminder in reminders if reminder]
        if not clean:
            return True
        if target.phase == "prepared" and target.state is not None:
            target.state.turn_reminders = (*target.state.turn_reminders, *clean)
            return True
        if self._active_turn_scope is target.scope and self._active_turn_state is not None:
            self._active_turn_state.turn_reminders = (*self._active_turn_state.turn_reminders, *clean)
            return True
        self._pending_current_run_hook_reminders.setdefault(target.scope, []).extend(clean)
        return True

    def remove_hook_reminders_for_current_run(
        self,
        target: CurrentRunReminderTarget,
        reminders: list[str],
    ) -> bool:
        """Withdraw queued hook reminders only if the captured target is still valid.

        Mirrors :meth:`queue_hook_reminders_for_current_run` for a mid-run
        injection cancelled after its commit: removes the last occurrence of
        each reminder from wherever it still awaits delivery (the scope's
        pending list or the turn state's reminder tuple), so a withdrawn
        prompt's hook and skill-reference reminders never reach the model.
        """
        if not self._is_current_run_target_valid(target):
            return False
        remaining = [reminder for reminder in reminders if reminder]
        if not remaining:
            return True
        pending = self._pending_current_run_hook_reminders.get(target.scope)
        if pending:
            for reminder in list(remaining):
                for i in range(len(pending) - 1, -1, -1):
                    if pending[i] == reminder:
                        del pending[i]
                        remaining.remove(reminder)
                        break
            if not pending:
                self._pending_current_run_hook_reminders.pop(target.scope, None)
        if not remaining:
            return True
        state = target.state if target.phase == "prepared" else None
        if state is None and self._active_turn_scope is target.scope:
            state = self._active_turn_state
        if state is None:
            return True
        turn_reminders = list(state.turn_reminders)
        for reminder in remaining:
            for i in range(len(turn_reminders) - 1, -1, -1):
                if turn_reminders[i] == reminder:
                    del turn_reminders[i]
                    break
        state.turn_reminders = tuple(turn_reminders)
        return True

    def update_skill_catalog_for_current_run(self, target: CurrentRunReminderTarget) -> bool:
        """Refresh the skill catalog only if the captured current-run target is current."""
        if not self._is_current_run_target_valid(target):
            return False
        if target.phase == "prepared" and target.state is not None:
            target.state.skill_catalog = self._snapshot_skill_catalog()
        elif self._active_turn_scope is target.scope and self._active_turn_state is not None:
            self._active_turn_state.skill_catalog = self._snapshot_skill_catalog()
        return True

    def set_skill_catalog_for_current_run(
        self,
        target: CurrentRunReminderTarget,
        skill_catalog: str | None,
    ) -> bool:
        """Set the skill catalog only if the captured current-run target is current."""
        if not self._is_current_run_target_valid(target):
            return False
        if target.phase == "prepared" and target.state is not None:
            target.state.skill_catalog = skill_catalog
        elif self._active_turn_scope is target.scope and self._active_turn_state is not None:
            self._active_turn_state.skill_catalog = skill_catalog
        return True

    def is_current_run_target_valid(self, target: CurrentRunReminderTarget) -> bool:
        """Return whether a captured current-run reminder target is still valid."""
        return self._is_current_run_target_valid(target)

    def expire_current_run_scope(self, reminder_scope: CurrentRunReminderScope) -> None:
        """Expire a current-run scope and discard stale reminders for it."""
        self._current_run_scopes.discard(reminder_scope)
        self._pending_current_run_hook_reminders.pop(reminder_scope, None)
        if self._active_turn_scope is reminder_scope:
            self._active_turn_scope = None
            self._active_turn_state = None
            self._turn_state.set(None)

    def set_last_words(self, text: str | None) -> None:
        """Set/clear the Phase 4 LAST_WORDS progress note.

        Called by ``UnifiedContextStrategy`` after Phase 4 drops the
        current turn's tool-call history.  The text is appended (as a
        ``<system-reminder>`` block) to the end of the user message's
        content array on every subsequent LLM call until the next turn.

        The current todo-list text is captured here, once, so the dynamic
        block only changes when the note itself changes (set/refresh/restore)
        — never per call.
        """
        state = self._ensure_turn_state()
        state.last_words = text or None
        state.last_words_todo = self._snapshot_todo_state() if state.last_words else None

    def get_last_words(self) -> str | None:
        """Return the current LAST_WORDS text (for incremental regeneration).

        Falls back to a restored-but-not-yet-consumed note so that saving a
        session that was restored and closed again without resuming the turn
        does not erase the persisted note.
        """
        state = self._current_turn_state()
        if state is not None and state.last_words is not None:
            return state.last_words
        return self._restored_last_words

    def append_manifest(self, entries: list[ManifestEntry]) -> None:
        """Append code-generated stubs, retaining the newest persisted entries."""
        if not entries:
            return
        state = self._ensure_turn_state()
        serialized = [*list(state.last_words_manifest or []), *(entry.to_state() for entry in entries)]
        state.last_words_manifest = serialized[-_MANIFEST_MAX_PERSISTED:]

    def mark_manifest_records_unavailable(self, relative_paths: frozenset[str] | set[str]) -> None:
        """Snapshot quota evictions into already-persisted manifest entries."""
        if not relative_paths:
            return
        state = self._ensure_turn_state()
        if not state.last_words_manifest:
            return
        updated: list[dict[str, Any]] = []
        for value in state.last_words_manifest:
            entry = ManifestEntry.from_state(value)
            if entry is None:
                continue
            if entry.relative_path in relative_paths and entry.available:
                entry = replace(entry, available=False)
            updated.append(entry.to_state())
        state.last_words_manifest = updated or None

    def get_last_words_manifest(self) -> list[dict[str, Any]]:
        """Return detached manifest state with current quota evictions applied."""
        state = self._current_turn_state()
        source = state.last_words_manifest if state is not None else self._restored_last_words_manifest
        return self._normalize_active_manifest(source)

    def snapshot_phase4_retry_state(self) -> Phase4RetrySnapshot:
        """Snapshot only the attempt-local, content-bearing Phase-4 state."""
        state = self._ensure_turn_state()
        manifest = self._normalize_active_manifest(state.last_words_manifest)
        return Phase4RetrySnapshot(
            last_words=state.last_words,
            last_words_todo=state.last_words_todo,
            last_words_manifest=tuple(manifest),
        )

    def restore_phase4_retry_state(self, snapshot: Phase4RetrySnapshot) -> None:
        """Restore LAST_WORDS content without rewinding turn-level safety accounting."""
        state = self._ensure_turn_state()
        state.last_words = snapshot.last_words
        # This is the todo text captured when the note was created.  Re-reading
        # the live todo provider here would change the restored note's context.
        state.last_words_todo = snapshot.last_words_todo
        manifest = self._normalize_active_manifest(snapshot.last_words_manifest)
        state.last_words_manifest = manifest or None

    def _normalize_active_manifest(self, source: object) -> list[dict[str, Any]]:
        """Validate manifest rows and synchronize live spill availability."""
        raw = source if isinstance(source, list | tuple) else ()
        entries = [entry for value in raw if (entry := ManifestEntry.from_state(value)) is not None]
        normalized: list[dict[str, Any]] = []
        for entry in entries[-_MANIFEST_MAX_PERSISTED:]:
            if (
                entry.available
                and entry.relative_path
                and self._spill_quota is not None
                and not self._spill_quota.is_record_available(entry.relative_path)
            ):
                entry = replace(entry, available=False)
            normalized.append(entry.to_state())
        return normalized

    def get_drop_round_breaker(self) -> DropRoundBreakerState:
        """Return the active/restored Phase-4 breaker, defaulting empty."""
        state = self._current_turn_state()
        source = state.last_words_breaker if state is not None else self._restored_last_words_breaker
        restored = DropRoundBreakerState.from_state(source) if source is not None else None
        return restored or DropRoundBreakerState()

    def set_drop_round_breaker(self, breaker: DropRoundBreakerState) -> None:
        """Unconditionally replace breaker state, including note-less failures."""
        state = self._ensure_turn_state()
        state.last_words_breaker = breaker.to_state()

    def get_last_words_breaker_state(self) -> dict[str, Any] | None:
        """Return persisted breaker state once Phase 4 has recorded activity."""
        breaker = self.get_drop_round_breaker()
        return breaker.to_state() if breaker != DropRoundBreakerState() else None

    def claim_context_pressure_notification(self) -> bool:
        """Claim the one context-pressure notification allowed per logical turn."""
        state = self._ensure_turn_state()
        if state.context_pressure_notified:
            return False
        state.context_pressure_notified = True
        return True

    def release_context_pressure_notification(self) -> None:
        """Release a failed synchronous notification attempt for a later retry."""
        self._ensure_turn_state().context_pressure_notified = False

    def get_catalog_pointer_record_count_state(self) -> int | None:
        """Return the persisted turn-start catalog count, including zero."""
        if self._catalog_pointer_snapshot_valid:
            return self._catalog_pointer_record_count
        return self._restored_catalog_pointer_record_count

    def refresh_last_words_reminder(self, messages: list[Any]) -> int | None:
        """Rewrite the ``[LAST_WORDS]`` reminder on a per-call message list.

        Phase 4 compaction runs *below* this middleware (inside the client's
        message prep), so the LLM call that triggered it was enriched before
        the new note existed — without this refresh, that call would go out
        with its tool-call history dropped but only a stale note (or none)
        in its place, and the model would restart the task from scratch.

        Rebuilds the last user message with the current note rendered
        exactly as the next call's enrichment will render it, keeping the
        request prefix byte-stable across calls.  The list entry is
        *replaced* with a fresh ``Message`` — the existing object is never
        mutated, because when enrichment was skipped it is the live history
        message.  ``additional_properties`` is shared by reference so
        exclusion flags keep writing through to the history object; the
        caller must recompute any token annotation riding in it, since the
        shared count still describes the pre-refresh contents.  Returns the
        index of the replaced entry, or ``None`` when the list was left
        unmodified.
        """
        message, idx = self._find_user_message(messages)
        if message is None:
            return None
        reminders = self._build_last_words_reminders()
        kept = [c for c in message.contents if not self._is_last_words_reminder_content(c)]
        if len(kept) == len(message.contents) and not reminders:
            return None
        refreshed = Message(message.role, [*kept, *(_wrap(r) for r in reminders)])
        refreshed.additional_properties = message.additional_properties
        messages[idx] = refreshed
        return idx

    @staticmethod
    def _is_last_words_reminder_content(content: Any) -> bool:
        """Whether a content item is a middleware-authored LAST_WORDS reminder.

        User-authored reminder tags are escaped during enrichment, so a raw
        wrapped ``[LAST_WORDS]`` block can only come from
        ``_build_last_words_reminders``.
        """
        return (
            content.type == "text"
            and content.text is not None
            and content.text.startswith(f"{REMINDER_TAG_OPEN}\n[LAST_WORDS] ")
        )

    def restore_last_words(self, text: str | None) -> None:
        """Stash a LAST_WORDS note restored from persisted session state.

        Session restore calls this on a freshly built middleware (no turn
        state exists yet).  The next ``prepare_turn(preserve_last_words=True)``
        — i.e. resuming the interrupted turn — picks the note up so the
        request after restart carries the same ``[LAST_WORDS]`` reminder an
        in-process retry would; starting a fresh turn discards it instead.

        The todo section is re-captured from the (already hydrated) tracker —
        callers must restore ``chrys_todos`` before restoring the note.
        """
        self._restored_last_words = text or None
        self._restored_last_words_todo = self._snapshot_todo_state() if self._restored_last_words else None

    def restore_last_words_manifest(
        self,
        value: object,
        *,
        available_relative_paths: frozenset[str] | set[str] | None = None,
    ) -> None:
        """Validate restored manifest state and snapshot record availability once."""
        if value is not None and not isinstance(value, list):
            logger.debug("Dropping malformed LAST_WORDS manifest state: expected list")
        raw_entries = value if isinstance(value, list) else []
        entries = [entry for item in raw_entries if (entry := ManifestEntry.from_state(item)) is not None]
        entries = entries[-_MANIFEST_MAX_PERSISTED:]
        if available_relative_paths is None:
            available_relative_paths = set()
            if self._session_root is not None:
                from chrys.service.context.compaction.spill import available_record_path

                available_relative_paths = {
                    entry.relative_path
                    for entry in entries
                    if entry.relative_path and available_record_path(self._session_root, entry.relative_path)
                }
        restored: list[dict[str, Any]] = []
        for entry in entries:
            available = not entry.relative_path or entry.relative_path in available_relative_paths
            restored.append(
                ManifestEntry(
                    record_id=entry.record_id,
                    group_id=entry.group_id,
                    record_dir=entry.record_dir,
                    relative_path=entry.relative_path,
                    turn=entry.turn,
                    round=entry.round,
                    sequence=entry.sequence,
                    tool=entry.tool,
                    display_argument=entry.display_argument,
                    outcome=entry.outcome,
                    size_chars=entry.size_chars,
                    assistant_text=entry.assistant_text,
                    available=entry.available and available,
                    no_record_reason=entry.no_record_reason,
                ).to_state()
            )
        self._restored_last_words_manifest = restored or None

    def restore_last_words_breaker(self, value: object) -> None:
        """Stash validated breaker state for the next preserving prepare."""
        breaker = DropRoundBreakerState.from_state(value)
        self._restored_last_words_breaker = breaker.to_state() if breaker is not None else None

    def restore_catalog_pointer_record_count(self, value: object) -> None:
        """Stash a validated turn-start catalog count for a restored retry."""
        if value is None:
            self._restored_catalog_pointer_record_count = None
            return
        if not isinstance(value, int) or isinstance(value, bool) or value < 0 or value > _STATE_INTEGER_MAX:
            logger.debug("Dropping malformed dropped-record catalog pointer count")
            self._restored_catalog_pointer_record_count = None
            return
        self._restored_catalog_pointer_record_count = value

    def restore_phase4_state(
        self,
        state: Mapping[str, Any] | None,
        *,
        available_relative_paths: frozenset[str] | set[str] | None = None,
    ) -> None:
        """Re-arm the persisted Phase-4 state family after a runtime rebuild."""
        state = state or {}
        self.restore_last_words(state.get("last_words"))
        self.restore_last_words_manifest(
            state.get("last_words_manifest"),
            available_relative_paths=available_relative_paths,
        )
        self.restore_last_words_breaker(state.get("last_words_breaker"))
        self.restore_catalog_pointer_record_count(state.get(CATALOG_POINTER_RECORD_COUNT_STATE_KEY))

    def queue_hook_reminders(self, reminders: list[str], *, for_next_turn: bool = False) -> None:
        """Queue hook-provided reminders for the current or next user turn."""
        clean = [r for r in reminders if r]
        if not clean:
            return
        state = None if for_next_turn else self._current_turn_state()
        if state is not None:
            state.turn_reminders = (*state.turn_reminders, *clean)
            return
        self._pending_hook_reminders.extend(clean)

    def update_skill_catalog_for_active_turn(self) -> None:
        """Refresh the active turn's skill-catalog reminder from the provider."""
        state = self._current_turn_state()
        if state is None:
            return
        state.skill_catalog = self._snapshot_skill_catalog()

    def set_profile_switch(self, from_label: str, to_label: str) -> None:
        """Set pending profile switch info."""
        self._pending_switch = {"from": from_label, "to": to_label}

    def update_profile_switch_to(self, to_label: str) -> None:
        """Update *to* for consecutive switches (keep original *from*)."""
        if self._pending_switch is not None:
            self._pending_switch["to"] = to_label

    @property
    def has_pending_switch(self) -> bool:
        return self._pending_switch is not None

    def snapshot_pending_switch(self) -> dict[str, str] | None:
        """Return a copy of pending profile-switch metadata, if any."""
        return self._pending_switch.copy() if self._pending_switch is not None else None

    @property
    def consumed_switch_to(self) -> str | None:
        """The display name we switched to, if consumed this turn."""
        return self._consumed_switch_to

    # ------------------------------------------------------------------
    # ChatMiddleware interface
    # ------------------------------------------------------------------

    async def process(
        self,
        context: ChatContext,
        call_next: Callable[[], Awaitable[None]],
    ) -> None:
        turn_reminders = self._build_reminders()
        last_words_reminders = self._build_last_words_reminders()
        applied_switch: tuple[str, str] | None = None
        # Replace user messages in the per-call shallow copy only.  This
        # defangs user-authored reminder tags without modifying the tool loop's
        # prepped_messages or SessionContext.input_messages.  Tool-result
        # messages are intentionally not escaped here.
        # ``ChatMiddlewareLayer`` always gives ``ChatContext`` a fresh mutable
        # list; the kernel constructor's public annotation is the broader
        # ``Sequence`` accepted at its external boundary.
        messages = cast("list[Message]", context.messages)
        _, last_user_idx = self._find_user_message(messages)
        for msg_idx, message in enumerate(messages):
            if message.role != "user":
                continue
            message_turn_reminders = turn_reminders if msg_idx == last_user_idx else []
            message_last_words_reminders = last_words_reminders if msg_idx == last_user_idx else []
            if message_turn_reminders or message_last_words_reminders or self._has_system_reminder_tags(message):
                messages[msg_idx] = self._create_enriched(
                    message,
                    message_turn_reminders,
                    message_last_words_reminders,
                )
                if msg_idx == last_user_idx:
                    state = self._current_turn_state()
                    if state is not None and state.file_change:
                        # Delivered means an established provider request, not
                        # a completed middleware chain: lazy streaming inner
                        # middleware returns a proxy from call_next() and only
                        # reaches the final handler at first stream
                        # consumption. Observers run immediately before every
                        # final-handler invocation, so a run cancelled before
                        # consumption keeps the notice requeueable.
                        def _mark_file_change_delivered(
                            _messages: Sequence[Message],
                            _state: _TurnReminderState = state,
                        ) -> None:
                            _state.file_change_delivered = True

                        context.request_message_observers.append(_mark_file_change_delivered)
                    switch = state.switch if state is not None else None
                    if switch is not None:
                        applied_switch = switch

        await call_next()
        if applied_switch is not None:
            self._consumed_switch_to = applied_switch[1]
            pending = self._pending_switch
            if (
                pending is not None
                and pending.get("from") == applied_switch[0]
                and pending.get("to") == applied_switch[1]
            ):
                self._pending_switch = None

