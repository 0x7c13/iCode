"""SystemReminderMiddleware — injects ``<system-reminder>`` tags per LLM call.

A ``ChatMiddleware`` that fires before each LLM call in the tool loop.
It replaces the last user message in ``context.messages`` (a per-call
shallow copy) with an enriched version whose original user contents come
first, followed by ``<system-reminder>`` tags (runtime environment,
context usage, profile switch).

Because ``ChatContext.messages`` is a **shallow copy** of the tool loop's
``prepped_messages``, replacing an element in the copy does not affect the
original list.  And ``SessionContext.input_messages`` (used by ``after_run``
for state persistence) is never touched — session state is **automatically
clean** without any restoration logic.

Turn reminders are stable for a logical turn: runtime environment,
previous-turn usage, profile-switch notices, and the runtime skill catalog are
snapshotted at ``prepare_turn()`` and reused for every LLM call in that turn.
User-initiated injection/retry may refresh the skill catalog before the next
model call because a newly added skill is a meaningful runtime capability
change.  LAST_WORDS is different: it is generated by mid-turn compaction and
remains dynamic. Keeping turn reminders stable avoids unnecessary
provider-side cache misses during tool loops; do not reintroduce per-call
timestamps or other volatile reminder text.

Escaping scope: this middleware defangs ``<system-reminder>`` tags in
user-role message content only.  Tool-result content (web fetches, file
reads, sub-agent output) is passed through verbatim — treat reminder-shaped
text in tool results as untrusted in downstream prompts and rely on the
model's own judgement, not on this middleware, to discount it.
"""

